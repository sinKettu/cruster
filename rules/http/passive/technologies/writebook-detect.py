import base64
from cruster import HttpRequest, HttpResponse, finding


def scan(_request: HttpRequest, response: HttpResponse):
    try:
        body = base64.b64decode(response.body).decode("latin-1")
    except Exception:
        body = ""
    headers = []
    for item in response.headers:
        try:
            value = base64.b64decode(item["value"]).decode("latin-1")
        except Exception:
            value = ""
        headers.append(item["name"] + ": " + value)
    header_match = "Set-Cookie: _writebook_session" in "\n".join(headers)
    body_match = "Made with Writebook" in body or "Writebook</h1>" in body
    if not header_match and not body_match:
        return []
    return [finding("writebook-detect")]
