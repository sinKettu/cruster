import base64
import re

from cruster import HttpRequest, HttpResponse, finding


def scan(request: HttpRequest, response: HttpResponse):
    target = request.uri.split("://", 1)[-1]
    target = target[target.find("/") :] if "/" in target else "/"
    target = target.split("#", 1)[0].split("?", 1)[0] or "/"
    if target not in ("/jolokia/version", "/actuator/jolokia/version"):
        return []

    try:
        body = base64.b64decode(response.body).decode("latin-1")
    except Exception:
        body = ""

    status_match = re.match(r"\s*(\d+)", response.status)
    if not status_match or int(status_match.group(1)) != 200:
        return []
    if not all(word in body for word in ('"timestamp":', '"protocol":', '"agent":')):
        return []

    return [finding("jolokia-detect")]
