def scan(_request: HttpRequest, response: HttpResponse):
    try:
        body = base64.b64decode(response.body).decode("latin-1")
    except Exception:
        body = ""

    headers = []
    header_values = {}
    for item in response.headers:
        name = item["name"]
        try:
            value = base64.b64decode(item["value"]).decode("latin-1")
        except Exception:
            value = ""
        headers.append(name + ": " + value)
        key = name.lower().replace("-", "_")
        header_values[key] = header_values.get(key, "") + (
            ("\n" if key in header_values else "") + value
        )

    header = "\n".join(headers)
    response_text = header + "\n\n" + body
    parts = {
        "body": body,
        "header": header,
        "all_headers": header,
        "response": response_text,
        "server": header_values.get("server", ""),
        "cf_cache_status": header_values.get("cf_cache_status", ""),
        "cf_ray": header_values.get("cf_ray", ""),
    }
    technologies = []
    for signature in TECHNOLOGY_SIGNATURES:
        value = parts.get(signature.get("part", "body"), "")
        patterns = signature.get("words") or signature.get("regex", ())
        if signature.get("case-insensitive"):
            value = value.lower()
            patterns = [pattern.lower() for pattern in patterns]

        if "words" in signature:
            matches = [pattern in value for pattern in patterns]
        else:
            matches = []
            for pattern in patterns:
                try:
                    matches.append(re.search(pattern, value) is not None)
                except re.error:
                    matches.append(False)

        matched = all(matches) if signature.get("condition") == "and" else any(matches)
        if matched and signature["name"] not in technologies:
            technologies.append(signature["name"])

    return [finding("tech-detect", extracted=technologies)] if technologies else []
